_REQUEST_FIELDS = (
    "schema_version",
    "release_version",
    "created_at",
    "inputs",
    "registries",
    "entries",
    "dataset_ids",
    "output_paths",
)
_OUTPUT_ROLES = ("cumulative", "boundary", "precision")
_MAX_INPUT_BYTES = 128 * 1024 * 1024


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Compose deterministic cumulative, Boundary and Precision "
            "Dataset releases."
        )
    )
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=ROOT,
        help="Root used to resolve content-addressed input references.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        help="Root for generated release artifacts; defaults to repo root.",
    )
    parser.add_argument(
        "--verify-existing",
        action="store_true",
        help="Require existing outputs to match regenerated bytes.",
    )
    return parser


def _real_directory(path: Path, label: str) -> Path:
    if path.is_symlink() or not path.is_dir():
        raise ContractError(f"{label}: expected real directory")
    return path.resolve()


def _read_regular(path: Path, label: str) -> bytes:
    if path.is_symlink():
        raise ContractError(f"{label}: symlink is denied")
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as exc:
        raise ContractError(f"{label}: cannot open regular file") from exc
    try:
        metadata = os.fstat(descriptor)
        if not stat.S_ISREG(metadata.st_mode):
            raise ContractError(f"{label}: expected regular file")
        if metadata.st_size > _MAX_INPUT_BYTES:
            raise ContractError(f"{label}: input exceeds size limit")
        chunks: list[bytes] = []
        remaining = _MAX_INPUT_BYTES + 1
        while remaining:
            chunk = os.read(descriptor, min(65_536, remaining))
            if not chunk:
                break
            chunks.append(chunk)
            remaining -= len(chunk)
        raw = b"".join(chunks)
        if len(raw) > _MAX_INPUT_BYTES:
            raise ContractError(f"{label}: input exceeds size limit")
        return raw
    finally:
        os.close(descriptor)


def _json_object(raw: bytes, label: str) -> dict[str, Any]:
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ContractError(f"{label}: invalid JSON") from exc
    if not isinstance(value, dict):
        raise ContractError(f"{label}: expected object")
    return value


def _load_request(path: Path) -> dict[str, Any]:
    raw = _read_regular(path, "request")
    value = _json_object(raw, "request")
    if raw != (canonical_json(value) + "\n").encode("utf-8"):
        raise ContractError("request: expected canonical JSON")
    return require_exact_fields(value, "request", _REQUEST_FIELDS)


def _repo_path(
    root: Path,
    relative_path: str,
    label: str,
) -> Path:
    reference = Path(relative_path)
    if (
        reference.is_absolute()
        or ".." in reference.parts
        or "\\" in relative_path
    ):
        raise ContractError(f"{label}: expected safe repo-relative path")
    candidate = root.joinpath(*reference.parts)
    resolved = candidate.resolve()
    try:
        resolved.relative_to(root)
    except ValueError as exc:
        raise ContractError(f"{label}: path escapes repo root") from exc
    current = root
    for part in reference.parts:
        current = current / part
        if current.is_symlink():
            raise ContractError(f"{label}: symlink component is denied")
    return candidate


def _verify_reference(
    root: Path,
    reference: FactoryArtifactReference,
    label: str,
) -> Path:
    path = _repo_path(root, reference.relative_path, label)
    raw = _read_regular(path, label)
    actual = "sha256:" + hashlib.sha256(raw).hexdigest()
    if actual != reference.content_hash:
        raise ContractError(f"{label}: reference hash drift")
    return path


def _load_dataset(
    root: Path,
    release_input: DatasetReleaseInput,
) -> tuple[Path, dict[str, Any]]:
    path = _verify_reference(
        root,
        release_input.dataset,
        f"inputs.{release_input.role}.dataset",
    )
    if release_input.provenance is not None:
        _verify_reference(
            root,
            release_input.provenance,
            f"inputs.{release_input.role}.provenance",
        )
    dataset = _json_object(
        _read_regular(path, f"inputs.{release_input.role}.dataset"),
        f"inputs.{release_input.role}.dataset",
    )
    errors = validate_dataset(
        dataset,
        path.parent,
        require_verified=True,
    )
    if errors:
        raise ContractError(
            f"inputs.{release_input.role}: invalid Dataset: {errors[0]}"
        )
    return path, dataset


def _validate_entry(
    root: Path,
    entry: VerifiedReleaseEntry,
    environment_registry: EnvironmentRegistry,
    source_registry: SourceRegistry,
) -> TaskManifest:
    task_path = _verify_reference(
        root,
        entry.task,
        f"entries.{entry.task_id}.task",
    )
    evidence_path = _verify_reference(
        root,
        entry.admission_evidence,
        f"entries.{entry.task_id}.admission_evidence",
    )
    task = TaskManifest.load(task_path)
    if task.task_id != entry.task_id:
        raise ContractError(
            f"entries.{entry.task_id}: Task identity mismatch"
        )
    task_errors = validate_manifest(task.data)
    if task_errors:
        raise ContractError(
            f"entries.{entry.task_id}: invalid Task: {task_errors[0]}"
        )
    if task.admission_status != "verified":
        raise ContractError(
            f"entries.{entry.task_id}: Task is not verified"
        )
    if task.runtime_tier != entry.runtime_tier:
        raise ContractError(
            f"entries.{entry.task_id}: runtime tier drift"
        )
    if not task.environment_ref or not task.source_ref:
        raise ContractError(
            f"entries.{entry.task_id}: Registry references are required"
        )
    environment = environment_registry.get(task.environment_ref)
    source = source_registry.get(task.source_ref)
    if task.runtime_tier != environment.runtime_tier:
        raise ContractError(
            f"entries.{entry.task_id}: Environment Registry tier drift"
        )
    if (
        task.source_loading_mode
        and task.source_loading_mode
        not in environment.source_loading_modes
    ):
        raise ContractError(
            f"entries.{entry.task_id}: Environment source loading drift"
        )
    if task.base_commit != source.commit:
        raise ContractError(
            f"entries.{entry.task_id}: Source Registry commit drift"
        )
    if (
        task.source_loading_mode
        and task.source_loading_mode not in source.source_loading_modes
    ):
        raise ContractError(
            f"entries.{entry.task_id}: Source loading drift"
        )
    task_dimension = task.problem_dimension or "unclassified"
    task_subclass = task.problem_subclass or "unclassified"
    if (
        task_dimension != entry.problem_dimension
        or task_subclass != entry.problem_subclass
    ):
        raise ContractError(
            f"entries.{entry.task_id}: taxonomy drift"
        )
    evidence = _json_object(
        _read_regular(
            evidence_path,
            f"entries.{entry.task_id}.admission_evidence",
        ),
        f"entries.{entry.task_id}.admission_evidence",
    )
    if evidence.get("task_id") != entry.task_id:
        raise ContractError(
            f"entries.{entry.task_id}: Admission identity mismatch"
        )
    hash_kind = evidence.get("task_manifest_hash_kind")
    if hash_kind == REPLAY_SPEC_HASH_KIND:
        expected_task_hash = replay_spec_hash(task)
    elif hash_kind is None:
        expected_task_hash = (
            "sha256:"
            + hashlib.sha256(
                _read_regular(
                    task_path,
                    f"entries.{entry.task_id}.task",
                )
            ).hexdigest()
        )
    else:
        raise ContractError(
            f"entries.{entry.task_id}: unsupported replay hash kind"
        )
    if evidence.get("task_manifest_hash") != expected_task_hash:
        raise ContractError(
            f"entries.{entry.task_id}: replay hash drift"
        )
    admission = evidence.get("admission")
    if not isinstance(admission, dict) or admission.get("verified") is not True:
        raise ContractError(
            f"entries.{entry.task_id}: Admission is not verified"
        )
    return task


def _dataset_ids(dataset: dict[str, Any]) -> set[str]:
    return {
        str(item["task_id"])
        for item in dataset["tasks"]
        if isinstance(item, dict) and item.get("task_id")
    }


def _verify_membership(
    entries: tuple[VerifiedReleaseEntry, ...],
    datasets: dict[str, dict[str, Any]],
) -> None:
    cumulative = _dataset_ids(datasets["cumulative_base"])
    precision = _dataset_ids(datasets["precision_base"])
    boundary = _dataset_ids(datasets["boundary_freeze"])
    for entry in entries:
        observed = (
            entry.task_id in cumulative,
            entry.task_id in precision,
            entry.task_id in boundary,
        )
        expected = {
            "inherited_cumulative": (True, False, False),
            "inherited_precision": (True, True, False),
            "restored_precision": (False, False, False),
            "factory_boundary": (False, False, True),
        }[entry.origin]
        if observed != expected:
            raise ContractError(
                f"entries.{entry.task_id}: source Dataset membership drift"
            )
    expected_cumulative = cumulative | {
        item.task_id
        for item in entries
        if item.origin in ("restored_precision", "factory_boundary")
    }
    observed_cumulative = {
        item.task_id for item in entries if "cumulative" in item.slices
    }
    expected_precision = precision | {
        item.task_id
        for item in entries
        if item.origin == "restored_precision"
    }
    observed_precision = {
        item.task_id for item in entries if "precision" in item.slices
    }
    observed_boundary = {
        item.task_id for item in entries if "boundary" in item.slices
    }
    if observed_cumulative != expected_cumulative:
        raise ContractError("entries: cumulative set algebra drift")
    if observed_precision != expected_precision:
        raise ContractError("entries: precision set algebra drift")
    if observed_boundary != boundary:
        raise ContractError("entries: boundary set algebra drift")


def _output_paths(
    value: object,
) -> dict[str, dict[str, str] | str]:
    data = require_exact_fields(
        value,
        "output_paths",
        ("release_manifest", *_OUTPUT_ROLES),
    )
    result: dict[str, dict[str, str] | str] = {
        "release_manifest": require_str(
            data["release_manifest"],
            "output_paths.release_manifest",
        )
    }
    for role in _OUTPUT_ROLES:
        selected = require_exact_fields(
            data[role],
            f"output_paths.{role}",
            ("dataset", "summary"),
        )
        result[role] = {
            "dataset": require_str(
                selected["dataset"],
                f"output_paths.{role}.dataset",
            ),
            "summary": require_str(
                selected["summary"],
                f"output_paths.{role}.summary",
            ),
        }
    return result


def _encoded_outputs(
    request: dict[str, Any],
    root: Path,
) -> dict[str, bytes]:
    inputs = tuple(
        DatasetReleaseInput.from_dict(
            item,
            path=f"request.inputs[{index}]",
        )
        for index, item in enumerate(
            require_list(request["inputs"], "request.inputs")
        )
    )
    registries_value = require_mapping(
        request["registries"],
        "request.registries",
    )
    registries = {
        key: FactoryArtifactReference.from_dict(
            item,
            path=f"request.registries.{key}",
        )
        for key, item in registries_value.items()
    }
    entries = tuple(
        VerifiedReleaseEntry.from_dict(
            item,
            path=f"request.entries[{index}]",
        )
        for index, item in enumerate(
            require_list(request["entries"], "request.entries")
        )
    )
    datasets: dict[str, dict[str, Any]] = {}
    for release_input in inputs:
        _, datasets[release_input.role] = _load_dataset(
            root,
            release_input,
        )
    registry_paths = {
        name: _verify_reference(
            root,
            reference,
            f"registries.{name}",
        )
        for name, reference in registries.items()
    }
    try:
        environment_registry = EnvironmentRegistry.load(
            registry_paths["environments"]
        )
        source_registry = SourceRegistry.load(
            registry_paths["sources"]
        )
    except KeyError as exc:
        raise ContractError(
            "registries: environments and sources are required"
        ) from exc
    tasks = {
        entry.task_id: _validate_entry(
            root,
            entry,
            environment_registry,
            source_registry,
        )
        for entry in entries
    }
    _verify_membership(entries, datasets)
    dataset_ids = require_mapping(
        request["dataset_ids"],
        "request.dataset_ids",
    )
    release = build_dataset_release(
        release_version=require_str(
            request["release_version"],
            "request.release_version",
        ),
        inputs=inputs,
        registries=registries,
        entries=entries,
        dataset_ids={
            key: require_str(value, f"request.dataset_ids.{key}")
            for key, value in dataset_ids.items()
        },
        created_at=require_str(
            request["created_at"],
            "request.created_at",
        ),
    )
    rebuilt = rebuild_release_datasets(release)
    paths = _output_paths(request["output_paths"])
    encoded: dict[str, bytes] = {
        str(paths["release_manifest"]): (
            canonical_json(release.to_dict()) + "\n"
        ).encode("utf-8")
    }
    by_task = {entry.task_id: entry for entry in entries}
    for role in _OUTPUT_ROLES:
        role_paths = paths[role]
        assert isinstance(role_paths, dict)
        dataset = rebuilt[role]
        output = next(item for item in release.outputs if item.role == role)
        metadata = {
            task_id: {
                "problem_dimension": by_task[task_id].problem_dimension,
                "problem_subclass": by_task[task_id].problem_subclass,
                "failure_contract": by_task[task_id].failure_contract,
            }
            for task_id in output.task_ids
        }
        summary = summarize_verified_dataset(
            dataset,
            dataset_hash=output.generated_dataset_hash,
            task_metadata=metadata,
        )
        encoded[role_paths["dataset"]] = (
            canonical_json(dataset) + "\n"
        ).encode("utf-8")
        encoded[role_paths["summary"]] = (
            canonical_json(summary) + "\n"
        ).encode("utf-8")
    if set(tasks) != {entry.task_id for entry in entries}:
        raise ContractError("entries: Task validation is incomplete")
    return encoded


def _target_path(
    root: Path,
    relative_path: str,
) -> Path:
    target = _repo_path(root, relative_path, "output path")
    current = root
    for part in Path(relative_path).parts[:-1]:
        current = current / part
        if current.exists() and not current.is_dir():
            raise ContractError(
                "output path: parent is not a directory"
            )
    return target


def _write_outputs(
    output_root: Path,
    encoded: dict[str, bytes],
    *,
    verify_existing: bool,
) -> None:
    targets = {
        relative: _target_path(output_root, relative)
        for relative in encoded
    }
    if len(targets) != len(set(targets.values())):
        raise ContractError("output paths: duplicate target")
    if verify_existing:
        for relative, target in targets.items():
            actual = _read_regular(target, f"output {relative}")
            if actual != encoded[relative]:
                raise ContractError(
                    f"output {relative}: existing bytes do not match"
                )
        return
    for relative, target in targets.items():
        if target.exists() or target.is_symlink():
            raise ContractError(
                f"output {relative}: target already exists"
            )
    created: list[Path] = []
    with tempfile.TemporaryDirectory(
        prefix=".opbench-release-",
        dir=output_root,
    ) as raw:
        staging = Path(raw)
        for relative, payload in encoded.items():
            stage_path = staging / relative
            stage_path.parent.mkdir(parents=True, exist_ok=True)
            stage_path.write_bytes(payload)
        try:
            for relative, target in targets.items():
                target.parent.mkdir(parents=True, exist_ok=True)
                os.replace(staging / relative, target)
                created.append(target)
        except BaseException:
            for target in reversed(created):
                target.unlink(missing_ok=True)
            raise


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        repo_root = _real_directory(
            args.repo_root.resolve(),
            "repo_root",
        )
        output_root = _real_directory(
            (
                args.output_root.resolve()
                if args.output_root is not None
                else repo_root
            ),
            "output_root",
        )
        request = _load_request(args.input)
        if request["schema_version"] != "v1":
            raise ContractError(
                "request.schema_version: expected 'v1'"
            )
        encoded = _encoded_outputs(request, repo_root)
        _write_outputs(
            output_root,
            encoded,
            verify_existing=args.verify_existing,
        )
    except (ContractError, OSError, ValueError) as exc:
        print(f"[release_invalid] {exc}", file=sys.stderr)
        return 2
    print(
        canonical_json(
            {
                "output_count": len(encoded),
                "status": (
                    "verified"
                    if args.verify_existing
                    else "composed"
                ),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
